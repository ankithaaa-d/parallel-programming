
import numpy as np


PRESYNAPTIC_EVENT = 0
POSTSYNAPTIC_EVENT = 1

EVENT_DTYPE = np.dtype([
    ("source", np.int64),
    ("destination", np.int64),
    ("synapse_id", np.int64),
    ("event_type", np.int8)
])


def validate_spikes(spikes, num_neurons, name):
    """
    Validate spike IDs received from the neuron simulation.
    """

    spikes = np.asarray(spikes)

    if spikes.ndim != 1:
        raise ValueError(
            f"{name} must be one-dimensional"
        )

    if spikes.size == 0:
        return np.empty(0, dtype=np.int64)

    if spikes.dtype.kind not in "iu":
        raise TypeError(
            f"{name} must contain integer neuron IDs"
        )

    spikes = spikes.astype(np.int64, copy=False)

    if np.any(spikes < 0) or np.any(spikes >= num_neurons):
        raise ValueError(
            f"{name} contains invalid neuron IDs"
        )

    if len(np.unique(spikes)) != len(spikes):
        raise ValueError(
            f"{name} contains duplicate neuron IDs"
        )

    return spikes


def collect_synaptic_events(
    connectivity,
    pre_spikes,
    post_spikes
):
    """
    Collect synaptic events from externally supplied spike queues.

    Parameters:
        connectivity:
            SharedConnectivity instance.

        pre_spikes:
            Presynaptic neuron IDs generated by the neuron model.

        post_spikes:
            Postsynaptic neuron IDs generated by the neuron model.

    Returns:
        Structured NumPy array containing:
            source
            destination
            synapse_id
            event_type

    Event types:
        PRESYNAPTIC_EVENT
        POSTSYNAPTIC_EVENT

    This function collects events only.
    STDP contributions are calculated separately.
    """

    num_neurons = connectivity.num_neurons

    pre_spikes = validate_spikes(
        pre_spikes,
        num_neurons,
        "pre_spikes"
    )

    post_spikes = validate_spikes(
        post_spikes,
        num_neurons,
        "post_spikes"
    )

    # Determine the number of events before allocation.
    pre_event_count = sum(
        connectivity.row_ptr[neuron + 1]
        - connectivity.row_ptr[neuron]
        for neuron in pre_spikes
    )

    post_event_count = sum(
        connectivity.csc_indptr[neuron + 1]
        - connectivity.csc_indptr[neuron]
        for neuron in post_spikes
    )

    total_events = int(
        pre_event_count + post_event_count
    )

    events = np.empty(
        total_events,
        dtype=EVENT_DTYPE
    )

    event_position = 0

    # Collect presynaptic events through CSR.
    for source in pre_spikes:

        destinations, synapse_ids = (
            connectivity.outgoing_connections(
                int(source)
            )
        )

        count = len(destinations)

        events["source"][
            event_position:event_position + count
        ] = source

        events["destination"][
            event_position:event_position + count
        ] = destinations

        events["synapse_id"][
            event_position:event_position + count
        ] = synapse_ids

        events["event_type"][
            event_position:event_position + count
        ] = PRESYNAPTIC_EVENT

        event_position += count

    # Collect postsynaptic events through CSC.
    for destination in post_spikes:

        sources, synapse_ids = (
            connectivity.incoming_connections(
                int(destination)
            )
        )

        count = len(sources)

        events["source"][
            event_position:event_position + count
        ] = sources

        events["destination"][
            event_position:event_position + count
        ] = destination

        events["synapse_id"][
            event_position:event_position + count
        ] = synapse_ids

        events["event_type"][
            event_position:event_position + count
        ] = POSTSYNAPTIC_EVENT

        event_position += count

    return events
